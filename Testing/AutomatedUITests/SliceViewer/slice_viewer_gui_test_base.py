def toolbar_action(presenter, text):
    """One of the SliceViewer toolbar's actions, by its ``ToolItemText`` name.

    The toolbar is a matplotlib navigation toolbar with Mantid's own items added, so its buttons are
    ``QAction``s rather than widgets and are reached through ``actions()`` rather than by object
    name. ``trigger()`` on one is what a click on it does.
    """
    for action in presenter.view.data_view.mpl_toolbar.actions():
        if action.text() == text:
            return action
    available = [action.text() for action in presenter.view.data_view.mpl_toolbar.actions() if action.text()]
    raise AssertionError(f"no toolbar action named '{text}'; available: {available}")


def create_md_workspaces():
    """The 4D and 3D MD workspaces and the peaks workspace from the guide's 'MDWorkspace (with
    events)' snippet, verbatim.

    ``SliceMD`` here warns about the ``SlicingAlgorithm``; the guide says so too, and it is
    harmless.
    """
    from mantid.simpleapi import (
        AddPeakHKL,
        CopySample,
        CreateMDWorkspace,
        CreatePeaksWorkspace,
        CreateSampleWorkspace,
        FakeMDEventData,
        SetUB,
        SliceMD,
    )

    md_4D = CreateMDWorkspace(
        Dimensions=4,
        Extents=[0, 2, -1, 1, -1.5, 1.5, -0.25, 0.25],
        Names="H,K,L,E",
        Frames="HKL,HKL,HKL,General Frame",
        Units="r.l.u.,r.l.u.,r.l.u.,meV",
        OutputWorkspace="md_4D",
    )
    FakeMDEventData(InputWorkspace=md_4D, UniformParams="5e5")
    FakeMDEventData(InputWorkspace=md_4D, UniformParams="1e5,0.5,1.5,-0.5,0.5,-0.75,0.75,-0.1,0.1")

    expt_info = CreateSampleWorkspace(OutputWorkspace="expt_info")
    md_4D.addExperimentInfo(expt_info)
    SetUB(Workspace="md_4D", c=2, gamma=120)

    md_3D = SliceMD(
        InputWorkspace="md_4D",
        AlignedDim0="H,0,2,100",
        AlignedDim1="K,-1,1,100",
        AlignedDim2="L,-1.5,1.5,100",
        OutputWorkspace="md_3D",
    )

    CreatePeaksWorkspace(InstrumentWorkspace="md_3D", NumberOfPeaks=0, OutputWorkspace="peaks")
    CopySample(InputWorkspace="md_3D", OutputWorkspace="peaks", CopyName=False, CopyMaterial=False, CopyEnvironment=False, CopyShape=False)
    AddPeakHKL(Workspace="peaks", HKL="1,0,1")
    AddPeakHKL(Workspace="peaks", HKL="1,0,0")
    return md_4D, md_3D


def create_cut_viewer_workspaces():
    """The six workspaces from the guide's CutViewer availability matrix, verbatim, keyed by name.

    Only ``ws_3D`` and ``ws_3D_QLab`` should offer the non-axis-aligned cut tool; the rest are there
    to prove it stays disabled, which is the whole of the guide's step 1.
    """
    from mantid.simpleapi import CreateMDWorkspace

    # OutputWorkspace is given explicitly for each. The guide's snippet assigns to a Python variable
    # and lets simpleapi take the name from it, which only works at module scope - inside a function
    # storing them in a dict there is no name to infer and the algorithm refuses to run.
    workspaces = {}
    workspaces["ws_2D"] = CreateMDWorkspace(
        Dimensions="2",
        Extents="-5,5,-4,4",
        Names="H,K",
        Units="r.l.u.,r.l.u.",
        Frames="HKL,HKL",
        SplitInto="2",
        SplitThreshold="50",
        OutputWorkspace="ws_2D",
    )
    workspaces["ws_3D"] = CreateMDWorkspace(
        Dimensions="3",
        Extents="-5,5,-4,4,-3,3",
        Names="H,K,L",
        Units="r.l.u.,r.l.u.,r.l.u.",
        Frames="HKL,HKL,HKL",
        SplitInto="2",
        SplitThreshold="50",
        OutputWorkspace="ws_3D",
    )
    workspaces["ws_3D_nonQdim"] = CreateMDWorkspace(
        Dimensions=3,
        Extents=[-1, 1, -1, 1, -1, 1],
        Names="E,H,K",
        Frames="General Frame,HKL,HKL",
        Units="meV,r.l.u.,r.l.u.",
        OutputWorkspace="ws_3D_nonQdim",
    )
    workspaces["ws_4D"] = CreateMDWorkspace(
        Dimensions=4,
        Extents=[-1, 1, -1, 1, -1, 1, -1, 1],
        Names="E,H,K,L",
        Frames="General Frame,HKL,HKL,HKL",
        Units="meV,r.l.u.,r.l.u.,r.l.u.",
        OutputWorkspace="ws_4D",
    )
    workspaces["ws_3D_QLab"] = CreateMDWorkspace(
        Dimensions="3",
        Extents="-5,5,-4,4,-3,3",
        Names="Q_lab_x,Q_lab_y,Q_lab_z",
        Units="U,U,U",
        Frames="QLab,QLab,QLab",
        SplitInto="2",
        SplitThreshold="50",
        OutputWorkspace="ws_3D_QLab",
    )
    return workspaces


def create_cut_viewer_data_workspace():
    """The ``ws`` of the guide's CutViewer step 3: a 3D HKL workspace with a non-orthogonal UB and
    one fake peak at (0,0,1)."""
    from mantid.simpleapi import CreateMDWorkspace, CreateSampleWorkspace, FakeMDEventData, SetUB

    ws = CreateMDWorkspace(
        Dimensions="3",
        Extents="-5,5,-4,4,-3,3",
        Names="H,K,L",
        Units="r.l.u.,r.l.u.,r.l.u.",
        Frames="HKL,HKL,HKL",
        SplitInto="2",
        SplitThreshold="50",
        OutputWorkspace="ws",
    )
    expt_info = CreateSampleWorkspace(OutputWorkspace="expt_info")
    SetUB(expt_info, 1, 1, 2, 90, 90, 120)
    ws.addExperimentInfo(expt_info)
    FakeMDEventData(ws, UniformParams="1e5", PeakParams="1e+05,0,0,1,0.3", RandomSeed="3873875")
    return ws


class SliceViewerGuiTestBase(AutomatedUITestBase):
    """Opens SliceViewer windows and closes every one of them at the end of the test.

    Windows are tracked rather than held singly because several guide sections open a second viewer
    on an exported workspace, and a viewer left open holds an ADS observer that fires into the next
    test's cleared ADS.
    """

    def setUp(self):
        super(SliceViewerGuiTestBase, self).setUp()
        self.viewers = []

    def tearDown(self):
        self._drain_async_tasks()
        for presenter in reversed(self.viewers):
            self.close_viewer(presenter)
        self.viewers = []
        process_events(2)
        super(SliceViewerGuiTestBase, self).tearDown()

    # ------------------------------------------------------------------ opening and closing

    def open_slice_viewer(self, workspace):
        """Open a workspace in SliceViewer, as 'right-click > Show Slice Viewer' does."""
        from mantidqt.widgets.sliceviewer.presenters.presenter import SliceViewer

        presenter = SliceViewer(workspace)
        process_events(3)
        self.viewers.append(presenter)
        return presenter

    def close_viewer(self, presenter):
        """Close a viewer, tolerating one the interface has already closed on its own.

        Several of the guide's checks are that SliceViewer *closes itself* when the workspace under
        it changes, so by teardown the window may be gone and its C++ half deleted.
        """
        try:
            if presenter.view is not None:
                # Disconnect the cursor tracker first. It stays connected to its canvas after the
                # window goes, and the *next* test's mouse events then reach it and call
                # ``cursorAt`` on a C++ widget that has been deleted - which prints a traceback into
                # the run for a window nothing is looking at any more.
                data_view = presenter.view.data_view
                if getattr(data_view, "_image_info_tracker", None) is not None:
                    data_view._image_info_tracker.disconnect()
                presenter.view.close()
        except (RuntimeError, AttributeError):
            pass
        process_events(2)

    @staticmethod
    def is_closed(presenter):
        """Whether a viewer has closed itself.

        ``clear_observer`` sets ``ads_observer`` to ``None`` on the way out and is the one signal
        that survives the window's own deletion, so it is what "the window should close" is checked
        against - reaching for ``view.isVisible()`` on a deleted widget raises instead.
        """
        return presenter.ads_observer is None

    # ------------------------------------------------------------------ toolbar

    def action(self, presenter, text):
        return toolbar_action(presenter, text)

    def toolbar_state(self, presenter, text):
        """``(enabled, checked)`` for a toolbar action - the pair every toolbar check needs."""
        action = toolbar_action(presenter, text)
        return action.isEnabled(), action.isChecked()

    def trigger(self, presenter, text):
        toolbar_action(presenter, text).trigger()
        process_events(3)

    # ------------------------------------------------------------------ plot and colour bar

    @staticmethod
    def data_view(presenter):
        return presenter.view.data_view

    @staticmethod
    def colorbar(presenter):
        return presenter.view.data_view.colorbar

    @staticmethod
    def dimensions(presenter):
        return presenter.view.data_view.dimensions

    @staticmethod
    def image_limits(presenter):
        """The colour limits currently applied to the image."""
        return presenter.view.data_view.image.get_clim()

    @staticmethod
    def axes_centre(presenter):
        axes = presenter.view.data_view.ax
        x_low, x_high = axes.get_xlim()
        y_low, y_high = axes.get_ylim()
        return 0.5 * (x_low + x_high), 0.5 * (y_low + y_high)

    def move_cursor(self, presenter, x=None, y=None):
        """Move the mouse over the colourfill plot, in data coordinates.

        Needed before an export keystroke with the line plot tool active: ``PixelLinePlot`` cuts
        through the pixel the cursor is over, and does nothing at all until a motion event has told
        it where that is.
        """
        from matplotlib.backend_bases import MouseEvent

        axes = presenter.view.data_view.ax
        if x is None or y is None:
            x, y = self.axes_centre(presenter)
        canvas = axes.figure.canvas
        x_pixel, y_pixel = axes.transData.transform((x, y))
        canvas.callbacks.process("motion_notify_event", MouseEvent("motion_notify_event", canvas, x_pixel, y_pixel))
        process_events(2)
        return x, y

    def draw_region(self, presenter, fraction=0.4):
        """Drag out a rectangle on the colourfill plot for the ROI tool.

        The rectangle is what ``RectangleSelectionLinePlot`` exports from, and it does not exist
        until a drag has created it - a bare keystroke with the ROI tool enabled exports nothing.
        The default covers the middle of the axes, comfortably past the selector's five pixel
        minimum in both directions.
        """
        from qt_interaction_helpers import mpl_drag

        axes = presenter.view.data_view.ax
        x_low, x_high = axes.get_xlim()
        y_low, y_high = axes.get_ylim()
        x_span, y_span = x_high - x_low, y_high - y_low
        start = (x_low + (0.5 - fraction / 2) * x_span, y_low + (0.5 - fraction / 2) * y_span)
        end = (x_low + (0.5 + fraction / 2) * x_span, y_low + (0.5 + fraction / 2) * y_span)
        mpl_drag(axes, start, end)
        process_events(3)
        return start, end

    def press_key(self, presenter, key):
        """Send one of the export keystrokes (``x``, ``y``, ``c``, ``r``) to the plot.

        Dispatched as a *release*, not a press: ``KeyHandler`` connects to ``key_release_event``,
        and the presenter's own ``key_pressed`` is a no-op. The event goes through the canvas's
        callback registry so that whichever tool is currently active picks it up, which is the whole
        point - the same keys mean different things to the pixel and rectangle tools.
        """
        from matplotlib.backend_bases import KeyEvent

        axes = presenter.view.data_view.ax
        canvas = axes.figure.canvas
        x_pixel, y_pixel = axes.transData.transform(self.axes_centre(presenter))
        canvas.callbacks.process("key_release_event", KeyEvent("key_release_event", canvas, key, x_pixel, y_pixel))
        process_events(3)

    def click_plot(self, presenter, x, y):
        """Click a point on the colourfill plot, in data coordinates."""
        from matplotlib.backend_bases import MouseEvent

        axes = presenter.view.data_view.ax
        canvas = axes.figure.canvas
        x_pixel, y_pixel = axes.transData.transform((x, y))
        event = MouseEvent("button_press_event", canvas, x_pixel, y_pixel, 1)
        event.inaxes = axes
        event.xdata, event.ydata = x, y
        presenter.canvas_clicked(event)
        process_events(3)

    # ------------------------------------------------------------------ dimensions

    @staticmethod
    def dimension_names(presenter):
        # ``Dimension.name`` is the QLabel that shows the name, not the name itself
        return [dim.name.text() for dim in presenter.view.data_view.dimensions.dims]

    def dimension(self, presenter, name):
        for dim in self.dimensions(presenter).dims:
            if dim.name.text() == name:
                return dim
        raise AssertionError(f"no dimension named '{name}'; found {self.dimension_names(presenter)}")

    def set_viewing_axes(self, presenter, x_name, y_name):
        """Choose which two dimensions are viewed, by clicking their X and Y buttons.

        Going through the buttons rather than setting the states directly is deliberate: swapping
        and transposing axes is itself one of the things the guide asks about, and the buttons are
        where that logic lives.
        """
        self.dimension(presenter, x_name).x.click()
        process_events(2)
        self.dimension(presenter, y_name).y.click()
        process_events(3)

    def viewed_axes(self, presenter):
        """``(x name, y name)`` of the two dimensions currently plotted."""
        from mantidqt.widgets.sliceviewer.views.dimensionwidget import State

        states = {dim.get_state(): dim.name.text() for dim in self.dimensions(presenter).dims}
        return states.get(State.X), states.get(State.Y)

    @staticmethod
    def supports_dynamic_rebinning(presenter):
        """Whether the interface offers a bins spin box on its viewed axes.

        This is the guide's "it should not support dynamic rebinning (can't change number of bins)"
        as a user sees it. ``DimensionWidget`` builds ``DimensionNonIntegrated`` - the only dimension
        class with a ``spinBins`` - when and only when the workspace can be rebinned, so the presence
        of that widget is the observable.
        """
        return all(hasattr(dim, "spinBins") for dim in presenter.view.data_view.dimensions.dims)
