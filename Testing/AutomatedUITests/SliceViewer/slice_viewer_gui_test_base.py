"""Shared setup and fixtures for the SliceViewer automated UI tests.

These replace ``dev-docs/source/Testing/SliceViewer/SliceViewer.rst``.

The guide is unusual among the manual guides in that almost all of its data is *generated by the
guide itself* - it prints the ``CreateMDWorkspace``/``FakeMDEventData``/``BinMD`` snippets the tester
is to paste into the script editor. Those snippets are reproduced here verbatim as fixtures, so the
workspaces under test are exactly the ones a tester would have had. Only the two MatrixWorkspace
files (``CNCS_7860_event.nxs`` and ``MAR11060.raw``) come from disk.

SliceViewer is opened the way the workbench opens it - ``SliceViewer(ws)`` - and the window is
``presenter.view``. Nearly everything the guide asks about is reachable from
``presenter.view.data_view``: the toolbar actions, the colour bar, the dimension widget and the
matplotlib axes.
"""

import os
import sys

_PARENT_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
if _PARENT_DIR not in sys.path:
    sys.path.insert(0, _PARENT_DIR)

from automated_ui_test_base import AutomatedUITestBase  # noqa: E402
from qt_interaction_helpers import process_events  # noqa: E402

# the two MatrixWorkspace files the guide names. It calls them TrainingCourseData; the repository's
# data store has both under Testing/Data/SystemTest, which the harness puts on the search path.
